// Экран выбора: сразу ничего не открываем, в вариантах — именно эти сны (первыми), и нет лишнего.
const CHOICE = [
  ["потеряла ребенка", ["Ребёнок", "Потерять вещь"]], ["замок", ["Ключи", "Дверь"]], ["первая любовь", ["Бывший", "Поцелуй"]],
  ["сабака", ["Собака"]]
];
// Не показывать в вариантах «может быть» и в подсказках (мусор из круга проверки).
const NEVER = [
  ["дом", ["Роды", "Пожар", "Мухи"]], ["пирог", ["Дверь"]], ["пожар", ["Подарок"]], ["машина", ["Стирка", "Малина"]],
  ["собирать грибы", ["Яйца", "Вишня"]], ["баран", ["Домовой"]], ["змеи в доме", ["Мухи", "Икона"]], ["вши у ребенка", ["Крещение"]],
  ["школьные годы", ["Новый год"]], ["крыша", ["Крыса"]], ["потолок течёт", ["Кровь"]], ["baba", ["Ведьма"]], ["свекла", ["Битое стекло"]],
  ["дед умер", ["Новый год", "Своя смерть"]], ["умер муж", ["Своя смерть"]], ["я умерла", ["Покойник"]]
];
const SUGGEST_BAD = [["сес", "Поезд"], ["мух", "Грибы"], ["бра", "Свадьба"]];

let fails = 0;
for (const [q, want, banned] of CASES) {
  const res = S.search(idx, q);
  const strong = res.filter((r) => r.strong);
  const opened = strong.length ? strong[0].d.title : null;
  const alts = strong.slice(1).filter((r) => r.score >= strong[0].score - 15).slice(0, 3).map((r) => r.d.title);
  const maybe = strong.length ? [] : res.slice(0, 5).map((r) => r.d.title);
  let ok = opened === want;
  if (banned) ok = ok && !banned.some((b) => alts.includes(b) || (opened === b && want !== b));
  if (!ok) fails++;
  console.log((ok ? "  ok   " : "  FAIL ") + q.padEnd(26) + " → " + (opened || "не открывать") +
    (alts.length ? " | возможно: " + alts.join(", ") : "") + (maybe.length ? " | может быть: " + maybe.join(", ") : ""));
}
for (const [q, want] of CHOICE) {
  const res = S.search(idx, q);
  const strong = res.filter((r) => r.strong);
  const maybe = res.slice(0, 5).map((r) => r.d.title);
  const ok = !strong.length && want.every((w, i) => maybe.slice(0, want.length).includes(w));
  if (!ok) fails++;
  console.log((ok ? "  ok   " : "  FAIL ") + ("выбор «" + q + "»").padEnd(26) + " → " + (strong.length ? "открыл " + strong[0].d.title : "может быть: " + maybe.join(", ")));
}
for (const [q, bad] of NEVER) {
  const res = S.search(idx, q);
  const strong = res.filter((r) => r.strong);
  const shown = strong.length ? strong.slice(0, 4).map((r) => r.d.title) : res.slice(0, 5).map((r) => r.d.title);
  const sug = S.search(idx, q, { suggest: true, limit: 6 }).map((r) => r.d.title);
  const hit = bad.filter((b) => shown.slice(strong.length ? 1 : 0).includes(b) || (sug.includes(b)));
  if (hit.length) fails++;
  console.log((hit.length ? "  FAIL " : "  ok   ") + ("без мусора «" + q + "»").padEnd(26) + " → " + shown.join(", ") + " | подсказки: " + (sug.join(", ") || "—"));
}
// «Похоже по написанию»: не больше 3 и только близкие; экран выбора vs опечатка.
for (const [q, want] of [["baba", []], ["свекла", []], ["крыша", []], ["абракадабра", []], ["собакка", ["Собака"]], ["кошкаа", ["Кошка"]]]) {
  const sim = S.similar(idx, q).map((d) => d.title);
  const ok = sim.length <= 3 && JSON.stringify(sim) === JSON.stringify(want);
  if (!ok) fails++;
  console.log((ok ? "  ok   " : "  FAIL ") + ("похоже «" + q + "»").padEnd(26) + " → " + (sim.join(", ") || "—"));
}
for (const [q, typo] of [["сабака", true], ["собакка", true], ["потеряла ребенка", false], ["замок", false], ["первая любовь", false]]) {
  const res = S.search(idx, q).slice(0, 5);
  const isTypo = res.length > 0 && res.every((r) => r.typo);
  const ok = isTypo === typo;
  if (!ok) fails++;
  console.log((ok ? "  ok   " : "  FAIL ") + ("«" + q + "»").padEnd(26) + " → " + (typo ? "«Точно такого сна нет» (опечатка)" : "«Выберите, что ближе к вашему сну»"));
}
// Синонимы не пересекаются: одно и то же слово — не у двух снов (кроме «~» — «на выбор»).
const owner = {};
const clash = [];
for (const d of window.DREAMS) for (const t of [d.title].concat(d.aliases)) {
  if (t.charAt(0) === "~") continue;
  const k = S.norm(t);
  if (owner[k] && owner[k] !== d.title) clash.push(t + ": " + owner[k] + " и " + d.title);
  owner[k] = d.title;
}
if (clash.length) fails++;
console.log((clash.length ? "  FAIL " : "  ok   ") + "синонимы без пересечений" + (clash.length ? ": " + clash.join("; ") : ""));

// Каждое название и каждый синоним открывают свой сон («~» — на выбор: сон в вариантах).
let selfMiss = [];
for (const d of window.DREAMS) {
  for (const t of [d.title].concat(d.aliases)) {
    if (t.charAt(0) === "~") {
      const res = S.search(idx, t.slice(1));
      if (res.some((r) => r.strong) || !res.slice(0, 5).some((r) => r.d.id === d.id)) selfMiss.push(t + " — не на выбор");
      continue;
    }
    const strong = S.search(idx, t).filter((r) => r.strong);
    if (!strong.length || strong[0].d.id !== d.id) selfMiss.push(t + " → " + (strong[0] ? strong[0].d.title : "ничего") + " (а надо " + d.title + ")");
  }
}
console.log((selfMiss.length ? "  info " : "  ok   ") + "названия и синонимы: промахов " + selfMiss.length);
selfMiss.forEach((m) => console.log("         " + m));
for (const [q, bad] of SUGGEST_BAD) {
  const sug = S.search(idx, q, { suggest: true, limit: 6 }).map((r) => r.d.title);
  const ok = !sug.includes(bad);
  if (!ok) fails++;
  console.log((ok ? "  ok   " : "  FAIL ") + ("подсказки «" + q + "»").padEnd(26) + " → " + (sug.join(", ") || "—"));
}
for (const q of ["соб", "зу", "не мо", "сабак", "покой"]) {
  console.log("       подсказки «" + q + "» → " + S.search(idx, q, { suggest: true, limit: 6 }).map((r) => r.d.title).join(", "));
}
console.log(fails ? "ПРОВАЛЕНО: " + fails : "Поиск в порядке.");
process.exit(fails ? 1 : 0);
